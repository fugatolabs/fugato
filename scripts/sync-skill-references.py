#!/usr/bin/env python3
"""Bundle Fugato's canonical docs for portable skill installation."""

import argparse
import os
from pathlib import Path
import re
import sys
from urllib.parse import urlsplit


ROOT = Path(__file__).resolve().parents[1]
SKILL = ROOT / "skills/fugato-workflow"
SOURCES = (
    "docs/guides/application-compatibility.md",
    "docs/guides/preparation.md",
    "docs/guides/local-resources.md",
    "docs/reference/environment.md",
    "docs/reference/mcp.md",
    "LICENSE",
    "NOTICE",
)
DESTINATIONS = {
    ROOT / source: (SKILL if source in ("LICENSE", "NOTICE") else SKILL / "references") / Path(source).name
    for source in SOURCES
}
DESTINATIONS[SKILL / "SKILL.md"] = SKILL / "SKILL.md"
LINK = re.compile(r"(\[[^\]]*\]\()([^\s)]+)(\))")


def bundled(source):
    if source.suffix != ".md":
        return source.read_text()
    destination = DESTINATIONS[source]

    def replace(match):
        target = match[2]
        if target.startswith("#") or urlsplit(target).scheme:
            return match[0]
        path, separator, anchor = target.partition("#")
        resolved = (source.parent / path).resolve()
        if resolved in DESTINATIONS:
            rewritten = os.path.relpath(DESTINATIONS[resolved], destination.parent)
        else:
            rewritten = "https://github.com/fugatolabs/fugato/blob/main/" + resolved.relative_to(ROOT).as_posix()
        return match[1] + rewritten + separator + anchor + match[3]

    return "<!-- Generated by scripts/sync-skill-references.py; edit the canonical docs. -->\n\n" + LINK.sub(replace, source.read_text())


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if bundled references are stale")
    args = parser.parse_args()
    stale = []
    for relative in SOURCES:
        source = ROOT / relative
        destination = DESTINATIONS[source]
        expected = bundled(source)
        if args.check:
            if not destination.exists() or destination.read_text() != expected:
                stale.append(str(destination.relative_to(ROOT)))
        else:
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_text(expected)
    if stale:
        print("Stale skill references: " + ", ".join(stale), file=sys.stderr)
        print("Run python3 scripts/sync-skill-references.py", file=sys.stderr)
        return 1
    print("Skill references are current" if args.check else "Updated skill references")
    return 0


if __name__ == "__main__":
    sys.exit(main())
