#!/usr/bin/env python3
"""Collect the exact Go dependency notices shipped in the four release targets."""
import argparse
import json
import os
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
MODULE = ROOT / 'packages/fugato'
TARGETS = ('darwin/amd64', 'darwin/arm64', 'linux/amd64', 'linux/arm64')


def run(*args, env=None):
    return subprocess.check_output(args, cwd=MODULE, env=env, text=True)


def collect():
    modules = {}
    decoder = json.JSONDecoder()
    for target in TARGETS:
        goos, goarch = target.split('/')
        data = run('go', 'list', '-deps', '-json', './cmd/fugato', './cmd/fugato-mcp',
                   env={**os.environ, 'GOOS': goos, 'GOARCH': goarch, 'CGO_ENABLED': '0'})
        while data.strip():
            entry, end = decoder.raw_decode(data.lstrip())
            data = data.lstrip()[end:]
            module = entry.get('Module', {})
            if module.get('Version'):
                if module.get('Replace'):
                    raise SystemExit('Release notices do not support replaced modules')
                modules[module['Path']] = module
    files = {}
    inventory = ['# Bundled third-party software', '',
                 'Generated by `scripts/generate-notices.py` from the dependencies linked into',
                 'the CLI and MCP binaries for macOS/Linux on AMD64/ARM64. Full upstream',
                 'license texts and attribution accompany this inventory in `third_party/`.',
                 'Regenerate when dependencies or the Go toolchain change.', '',
                 '| Component | Version | License summary | Notices |', '| --- | --- | --- | --- |']
    for name, module in sorted(modules.items()):
        directory = Path(module['Dir'])
        notices = sorted(p for p in directory.iterdir() if p.is_file() and
                         p.name.upper().startswith(('LICENSE', 'COPYING', 'NOTICE', 'AUTHORS', 'PATENTS')))
        if not notices:
            raise SystemExit(f'No license found for {name}')
        links = []
        for source in notices:
            path = f'{name}/{source.name}'
            files[path] = source.read_bytes()
            links.append(f'[{source.name}](third_party/{path})')
        license_text = (directory / 'LICENSE').read_text()
        if name == 'gopkg.in/yaml.v3':
            summary = 'MIT and Apache-2.0 (by file)'
        elif 'Permission is hereby granted' in license_text:
            summary = 'MIT'
        elif 'Neither the name' in license_text or 'Neither the names' in license_text:
            summary = 'BSD-3-Clause'
        else:
            raise SystemExit(f'Classify changed license for {name}')
        if name == 'modernc.org/libc':
            summary += '; embedded notices below'
        if name == 'modernc.org/sqlite':
            summary += '; SQLite public domain; sqlite-vec MIT'
        inventory.append(f"| {name} | {module['Version']} | {summary} | {', '.join(links)} |")
    goroot = Path(run('go', 'env', 'GOROOT').strip())
    goversion = run('go', 'env', 'GOVERSION').strip()
    for name in ('LICENSE', 'PATENTS'):
        if (goroot / name).is_file():
            files[f'go/{name}'] = (goroot / name).read_bytes()
    # Go ships vendored implementations inside its standard library. Preserve
    # their own notices too, including notices for platform-specific files.
    for source in sorted((goroot / 'src/vendor').rglob('*')):
        if source.is_file() and source.name.upper().startswith(('LICENSE', 'COPYING', 'NOTICE', 'PATENTS')):
            files[f'go/vendor/{source.relative_to(goroot / "src/vendor")}'] = source.read_bytes()
    inventory.extend([f'| Go runtime and standard library | {goversion} | BSD-3-Clause with vendored notices | [LICENSE](third_party/go/LICENSE), vendored notices under `third_party/go/vendor/` |', '',
                      'The optional Cursor VSIX contains only Fugato code, schema, and artwork.',
                      'It imports the editor API and Node built-ins supplied by Cursor; it bundles',
                      'no npm runtime packages. npm development/build dependencies are excluded',
                      'by `.vscodeignore` and `vsce package --no-dependencies`.', '',
                      'SQLite upstream material is covered by the included `LICENSE-SQLITE`;',
                      'modernc wrappers and libc include their own notices and embedded third-party',
                      'notices. The upstream files are preserved verbatim, including multiple',
                      'license choices and component-specific terms.', ''])
    return files, '\n'.join(inventory).encode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if checked-in notices are stale')
    args = parser.parse_args()
    files, inventory = collect()
    desired = {ROOT / 'THIRD_PARTY_NOTICES.md': inventory}
    desired.update({ROOT / 'third_party' / name: data for name, data in files.items()})
    existing = set((ROOT / 'third_party').rglob('*')) if (ROOT / 'third_party').exists() else set()
    extra = {p for p in existing if p.is_file()} - set(desired)
    if args.check:
        stale = [str(p.relative_to(ROOT)) for p, data in desired.items() if not p.exists() or p.read_bytes() != data]
        if stale or extra:
            raise SystemExit('Regenerate notices: ' + ', '.join(stale + [str(p.relative_to(ROOT)) for p in extra]))
        print(f'Notices match {len(files)} upstream files across {len(TARGETS)} targets')
        return
    for path in extra:
        path.unlink()
    for path, data in desired.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    print(f'Wrote inventory and {len(files)} upstream notice files')


if __name__ == '__main__':
    main()
