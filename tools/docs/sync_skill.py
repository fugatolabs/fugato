#!/usr/bin/env python3
"""Bundle Fugato's canonical docs for portable skill installation."""

import argparse
import os
from pathlib import Path
import re
import sys
from urllib.parse import urlsplit


ROOT = Path(__file__).resolve().parents[2]
SKILL = ROOT / "skills/fugato-workflow"
EMBEDDED = ROOT / "packages/fugato/internal/agentsetup/skill"
SOURCES = (
    "docs/guides/application-compatibility.md",
    "docs/guides/preparation.md",
    "docs/guides/local-resources.md",
    "docs/reference/environment.md",
    "docs/reference/mcp.md",
    "LICENSE",
    "NOTICE",
)
DESTINATIONS = {
    ROOT / source: (SKILL if source in ("LICENSE", "NOTICE") else SKILL / "references") / Path(source).name
    for source in SOURCES
}
DESTINATIONS[SKILL / "SKILL.md"] = SKILL / "SKILL.md"
LINK = re.compile(r"(\[[^\]]*\]\()([^\s)]+)(\))")


def bundled(source):
    if source.suffix != ".md":
        return source.read_text()
    destination = DESTINATIONS[source]

    def replace(match):
        target = match[2]
        if target.startswith("#") or urlsplit(target).scheme:
            return match[0]
        path, separator, anchor = target.partition("#")
        resolved = (source.parent / path).resolve()
        if resolved in DESTINATIONS:
            rewritten = os.path.relpath(DESTINATIONS[resolved], destination.parent)
        else:
            rewritten = "https://github.com/fugatolabs/fugato/blob/main/" + resolved.relative_to(ROOT).as_posix()
        return match[1] + rewritten + separator + anchor + match[3]

    return "<!-- Generated by tools/docs/sync_skill.py; edit the canonical docs. -->\n\n" + LINK.sub(replace, source.read_text())


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if bundled references are stale")
    args = parser.parse_args()
    stale = []
    for relative in SOURCES:
        source = ROOT / relative
        destination = DESTINATIONS[source]
        expected = bundled(source)
        if args.check:
            if not destination.exists() or destination.read_text() != expected:
                stale.append(str(destination.relative_to(ROOT)))
        else:
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_text(expected)
    # The installed CLI carries the same complete skill without requiring a
    # checkout or a separate language runtime on the user's machine.
    expected_files = {path.relative_to(SKILL): path.read_bytes()
                      for path in SKILL.rglob('*') if path.is_file()}
    for relative, data in expected_files.items():
        destination = EMBEDDED / relative
        if args.check:
            if not destination.is_file() or destination.read_bytes() != data:
                stale.append(str(destination.relative_to(ROOT)))
        else:
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(data)
    for path in EMBEDDED.rglob('*'):
        if path.is_file() and path.relative_to(EMBEDDED) not in expected_files:
            if args.check:
                stale.append(str(path.relative_to(ROOT)))
            else:
                path.unlink()
    if stale:
        print("Stale skill references: " + ", ".join(stale), file=sys.stderr)
        print("Run python3 tools/docs/sync_skill.py", file=sys.stderr)
        return 1
    print("Skill references are current" if args.check else "Updated skill references")
    return 0


if __name__ == "__main__":
    sys.exit(main())
